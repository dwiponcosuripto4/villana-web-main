import { redirect, isRedirect } from "@sveltejs/kit";
import type { RequestHandler } from "./$types";
import { google, getGoogleUser } from "$lib/server/auth/google";
import { db } from "$lib/server/db";
import { user } from "$lib/server/db/schema";
import { eq, or } from "drizzle-orm";
import {
  createSession,
  generateSessionToken,
  setSessionTokenCookie,
} from "$lib/server/auth";
import { encodeBase64url } from "@oslojs/encoding";

// generateUserId function removed - using serial integer IDs now

export const GET: RequestHandler = async (event) => {
  const { url, cookies } = event;
  const code = url.searchParams.get("code");
  const state = url.searchParams.get("state");
  const storedState = cookies.get("google_oauth_state");
  const codeVerifier = cookies.get("google_code_verifier");

  if (!code || !state || !storedState || state !== storedState || !codeVerifier) {
    return new Response("Invalid OAuth state", { status: 400 });
  }

  // Clear the OAuth cookies
  cookies.delete("google_oauth_state", { path: "/" });
  cookies.delete("google_code_verifier", { path: "/" });

  try {
    const tokens = await google.validateAuthorizationCode(code, codeVerifier);
    const googleUser = await getGoogleUser(tokens.accessToken());

    if (!googleUser) {
      return new Response("Failed to get user info from Google", {
        status: 400,
      });
    }

    // Check if user already exists by Google ID or email
    const existingUser = await db
      .select()
      .from(user)
      .where(
        or(eq(user.googleId, googleUser.id), eq(user.email, googleUser.email)),
      )
      .limit(1);

    let userId: string;

    if (existingUser.length > 0) {
      // User exists, update Google ID if not set
      const dbUser = existingUser[0];
      userId = dbUser.id;

      if (!dbUser.googleId) {
        await db
          .update(user)
          .set({
            googleId: googleUser.id,
            profilePicture: googleUser.picture,
            registrationMethod: "google",
          })
          .where(eq(user.id, dbUser.id));
      }
    } else {
      // Create new user (ID will be auto-generated by database serial)
      // Generate username from email and a random suffix
      const baseUsername = googleUser.email.split("@")[0];
      const randomSuffix = Math.random().toString(36).substring(2, 6);
      const username = baseUsername + "_" + randomSuffix;

      const newUser = await db.insert(user).values({
        username,
        email: googleUser.email,
        fullName: googleUser.name,
        googleId: googleUser.id,
        emailVerified: googleUser.verified_email,
        profilePicture: googleUser.picture,
        registrationMethod: "google",
        role: "viewer",
      }).returning();

      userId = newUser[0].id;

      // Redirect to complete profile form for phone and address
      const sessionToken = generateSessionToken();
      const session = await createSession(sessionToken, userId);
      setSessionTokenCookie(event, sessionToken, session.expiresAt);

      throw redirect(302, "/auth/google/complete-profile");
    }

    // Create session and redirect to dashboard
    const sessionToken = generateSessionToken();
    const session = await createSession(sessionToken, userId);
    setSessionTokenCookie(event, sessionToken, session.expiresAt);

    throw redirect(302, "/dashboard");
  } catch (error) {
    // Re-throw redirects (they're not errors)
    if (isRedirect(error)) {
      throw error;
    }
    console.error("OAuth callback error:", error);
    return new Response("OAuth authentication failed", { status: 500 });
  }
};
